type ConceptSeed = Omit<Concept, 'parentId' | 'box' | 'lastSeenAt' | 'nextReviewAt'> & {
  box?: number
  seenAgo?: number
  reviewIn?: number | null
}

function concept(seed: ConceptSeed): Concept {
  const { seenAgo, reviewIn, box, ...rest } = seed
  return {
    ...rest,
    parentId: null,
    box: box ?? 1,
    lastSeenAt: seenAgo === undefined ? null : isoAgo(seenAgo),
    nextReviewAt: reviewIn === undefined || reviewIn === null ? null : isoDayAt(reviewIn, 9),
  }
}

