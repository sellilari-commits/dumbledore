/**
 * Recognising an AI chat by its composer: the text box the student is typing into.
 *
 * The helper reports the focused element on every focus change and while the student types
 * (`focus.changed`: role, placeholder, frame). A *composer* is an editable, non-secure text area
 * or field that is not a search box and is wide relative to its window. On its own that proves
 * nothing (Slack, WhatsApp and Gmail have composers too), so an unknown chat also needs evidence
 * that an AI answers: an AI-flavoured placeholder ("Send a message to the model"), a disclaimer
 * ("LLMs can make mistakes"), a model name ("llama3.2:latest", "GPT-5"), AI chat controls
 * ("New chat", "Regenerate"), an AI window title, a local host (Open WebUI on localhost).
 * Messaging-style placeholders ("Message #general", "Type a message") earn little, so a
 * messenger never reaches the bar without real AI evidence.
 */
import type { Rect } from '@shared/geometry'
import type { FocusedElement } from '@shared/helper-protocol'
import { parseUrl } from '../../privacy/url'
import { ASSISTANTS, type AssistantConfig } from './assistants'

/** The focused composer, as far as detection needs it. */
export interface ComposerHint {
  pid: number
  placeholder: string | null
  multiline: boolean
}

export type FocusLike = Pick<
  FocusedElement,
  'pid' | 'role' | 'subrole' | 'editable' | 'isSecure' | 'placeholder' | 'frame'
>

const COMPOSER_ROLES = new Set(['AXTextArea', 'AXTextField'])
const SEARCH_PLACEHOLDER = /\b(search|find|filter|url|address|go to|jump to|to:|subject)\b/i

export const norm = (s: string): string =>
  s.toLowerCase().replace(/…/g, '...').replace(/\s+/g, ' ').trim()

/** The focused element as a composer, or null when it can't be a chat input. */
export function composerOf(el: FocusLike | null, windowFrame?: Rect | null): ComposerHint | null {
  if (!el?.editable || el.isSecure) return null
  if (!COMPOSER_ROLES.has(el.role) || el.subrole === 'AXSearchField') return null
  const placeholder = el.placeholder?.trim() || null
  if (placeholder && SEARCH_PLACEHOLDER.test(placeholder)) return null
  const f = el.frame
  if (f) {
    const minWidth = windowFrame ? Math.min(320, windowFrame.width * 0.3) : 200
    if (f.width < minWidth) return null
  }
  return { pid: el.pid, placeholder, multiline: el.role === 'AXTextArea' }
}

const strip = (s: string): string => norm(s).replace(/[.?!:]+$/, '')

/** Placeholders and markers that name their assistant ("Message Copilot", "Ask Gemini"). */
const NAMED: { assistant: AssistantConfig; markers: string[] }[] = ASSISTANTS.map((a) => {
  const name = a.name.toLowerCase()
  const markers = [...a.placeholders, ...a.textMarkers].map(strip).filter((m) => m.includes(name))
  return { assistant: a, markers: [...new Set(markers)] }
}).filter((n) => n.markers.length > 0)

/** The known assistant a composer placeholder names, e.g. Copilot in Edge's sidebar. */
export function assistantByPlaceholder(placeholder: string | null): AssistantConfig | null {
  if (!placeholder) return null
  const p = strip(placeholder)
  return NAMED.find((n) => n.markers.some((m) => p.startsWith(m)))?.assistant ?? null
}

const AI_WORDS =
  /\b(ai|assistant|model|llm|gpt[\w.-]*|chatbot|bot|prompt|llama[\w.:-]*|mistral|qwen[\w.:-]*|gemma[\w.:-]*|deepseek|claude|gemini|copilot|ollama)\b/i
const PROMPT_PLACEHOLDER =
  /^(ask\b|how can i help|what can i help|how can .{1,24} help|what do you want to (know|ask)|what's on your mind|what would you like|send a message|send a prompt|enter (a|your) (prompt|message|question)|type (a|your) (prompt|question)|write (a|your) prompt|start typing a prompt|chat with|talk to|ask me anything|describe\b)/
const MESSAGING_PLACEHOLDER =
  /^(message\b|type a (new )?message|write a message|reply\b|text message|imessage|aa$)/
const MESSAGING_TARGET = /^message\s*[#@]/

const DISCLAIMER =
  /\b((can|may) make mistakes|may (display|produce|generate|give|provide) inaccurate|ai[- ]generated|generated by ai|check important info|verify important (info|information)|responses may be inaccurate)\b/i
const MODEL =
  /\b(gpt-?\d[\w.-]*|gpt-oss[\w.:-]*|o\d-(mini|pro)|claude[ -]?(\d|sonnet|opus|haiku)[\w.-]*|sonnet \d[\w.]*|opus \d[\w.]*|gemini[ -]\d[\w.-]*|gemma[\w.:-]*|llama[ -]?\d[\w.:-]*|llama3[\w.:-]*|mistral[\w.:-]*|mixtral[\w.:-]*|ministral[\w.:-]*|qwen[\d.]*[\w.:-]*|deepseek[\w.:-]*|phi-?\d[\w.:-]*|grok[ -]?\d[\w.-]*|glm-?\d[\w.-]*|kimi[ -]k\d[\w.-]*|command[ -]r[\w+-]*)\b/i
const AI_CONTROLS =
  /^(new chat|regenerate( response)?|stop generating|system prompt|temperature|select a model|choose a model|model settings|tokens?\/s|\d+(\.\d+)? tok\/s|thought for \d+.*|deep research|search the web|think longer)$/i
const AI_TITLE = /\b(ai|assistant|llm|gpt|llama|ollama|open webui|librechat|lm studio|chatbot)\b/i
const CHAT_PATH = /^\/(c|chat|chats|conversation|conversations|thread|threads|t)(\/|$)/i
const LOCAL_HOST =
  /^(localhost|127\.\d+\.\d+\.\d+|0\.0\.0\.0|\[?::1\]?|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|[\w-]+\.local)$/

export type PlaceholderKind = 'ai' | 'prompt' | 'messaging' | 'other' | 'none'

export interface ChatEvidence {
  score: number
  /** At least one signal that only an AI chat gives (not a messenger). */
  ai: boolean
  placeholder: PlaceholderKind
}

export interface EvidenceInput {
  placeholder: string | null
  lines: readonly { text: string; align: 'left' | 'center' | 'right' | null }[]
  title: string | null
  url: string | null
}

const MAX_LINE = 120

export function chatEvidence(input: EvidenceInput): ChatEvidence {
  let score = 0
  let ai = false
  const ph = input.placeholder ? strip(input.placeholder) : null
  const placeholder = placeholderKind(ph)
  if (placeholder === 'ai') {
    score += 3
    ai = true
  } else if (placeholder === 'prompt') score += 2
  else if (placeholder === 'messaging') score += 1
  const short = input.lines.filter((l) => l.text.length <= MAX_LINE)
  const texts = short.map((l) => l.text.trim())
  if (texts.some((t) => DISCLAIMER.test(t))) {
    score += 3
    ai = true
  }
  if (texts.some((t) => t.length <= 48 && MODEL.test(t))) {
    score += 2
    ai = true
  }
  const controls = texts.filter((t) => AI_CONTROLS.test(t)).length
  if (controls > 0) {
    score += Math.min(2, controls)
    ai = true
  }
  if (!ph && texts.some((t) => t.length <= 60 && PROMPT_PLACEHOLDER.test(strip(t)))) score += 1
  if (input.title && AI_TITLE.test(input.title)) {
    score += 1
    ai = true
  }
  const url = parseUrl(input.url)
  if (url?.host && LOCAL_HOST.test(url.host)) score += 1
  if (url?.host && CHAT_PATH.test(url.path)) score += 1
  const aligns = new Set(short.map((l) => l.align))
  if (aligns.has('right') && aligns.has('left')) score += 1
  return { score, ai, placeholder }
}

function placeholderKind(ph: string | null): PlaceholderKind {
  if (!ph) return 'none'
  if (MESSAGING_TARGET.test(ph)) return 'other' // "Message #general", "Message @sam"
  if (AI_WORDS.test(ph)) return 'ai'
  if (PROMPT_PLACEHOLDER.test(ph)) return 'prompt'
  if (MESSAGING_PLACEHOLDER.test(ph)) return 'messaging'
  return 'other'
}

/**
 * Points an unknown chat needs, by what its placeholder says: a prompt-style or AI placeholder
 * needs the least, a messenger-style one ("Type a message") or none at all needs strong AI
 * evidence, and any other placeholder ("Write a comment…", "Add a caption") is not a composer.
 */
export const UNKNOWN_CHAT_MIN_SCORE: Record<PlaceholderKind, number | null> = {
  ai: 5,
  prompt: 5,
  messaging: 7,
  none: 6,
  other: null,
}

export function isUnknownChat(hint: ComposerHint, evidence: ChatEvidence): boolean {
  if (!evidence.ai) return false
  if (evidence.placeholder === 'none' && !hint.multiline) return false
  const min = UNKNOWN_CHAT_MIN_SCORE[evidence.placeholder]
  return min !== null && evidence.score >= min
}
