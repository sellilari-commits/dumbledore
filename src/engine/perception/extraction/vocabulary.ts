export function isAcademicWord(token: string): boolean {
  const t = token.toLowerCase()
  if (EXACT.has(t)) return true
  if (t.length < 5) return false
  return STEMS.some((s) => t.startsWith(s))
}

/** Share of words that are academic vocabulary (0–1) and the word count. */
export function academicDensity(text: string): { density: number; words: number } {
  const tokens = text.match(/\p{L}[\p{L}'’-]*/gu) ?? []
  if (tokens.length === 0) return { density: 0, words: 0 }
  let hits = 0
  for (const t of tokens) if (isAcademicWord(t)) hits++
  return { density: hits / tokens.length, words: tokens.length }
}

/** Maths notation per 100 characters. */
export function mathDensity(text: string): number {
  if (!text) return 0
  const m = text.match(/[=∑∫√±→≤≥∞∂∆Δπθλμσ^≈≠∈∀∃]/g)
  return ((m?.length ?? 0) * 100) / text.length
}
