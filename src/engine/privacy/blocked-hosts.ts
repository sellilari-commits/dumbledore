const HOST_ENTRIES: readonly { pattern: string; category: HostCategory }[] = (
  Object.entries(BLOCKED_HOSTS) as [HostCategory, readonly string[]][]
).flatMap(([category, patterns]) => patterns.map((pattern) => ({ pattern, category })))

export function allBlockedHostEntries(): readonly { pattern: string; category: HostCategory }[] {
  return HOST_ENTRIES
}
